"""The job folder: exact copies under send/, job.json and job.md (spec REQ-DATA-d985bb3d section 5;
REQ-DATA-14b295ed), and their verification before a cloud run (REQ-SEC-450de6ab, REQ-SEC-11ca382d)."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
from pathlib import Path, PurePosixPath
from typing import Any

from . import CLI_SHA, CLI_VERSION, ENDPOINT, FORMAT, JOB_KIND, NOTE, TOOL, USAGE, VERSION, diagram, scenario, workspace
from .project import flash_parts, sha256_file
from .report import refused, stamp, write_json, write_text

SEND = "send"
TRANSMITTED = ("diagram", "firmware", "flash", "elf")
VIRTUAL_RANGE = (100, 600_000)
REAL_RANGE = (10, 1800)


def default_budget(virtual_ms: int) -> int:
    return min(REAL_RANGE[1], max(60, 30 + 4 * -(-virtual_ms // 1000)))


def _copy(source: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)


FIRMWARE_FORMS = ("hex", "bin", "uf2", "elf")
FLASH_CONFIG = "flash/flasher_args.json"
ELF_NAME = "firmware.elf"
TEXT_LIMIT = 256


def firmware_name(form: str) -> str:
    return FLASH_CONFIG if form == "esp-idf-flasher-args" else f"firmware.{form}"


def config_text(firmware: str, elf: str | None) -> str:
    """The only wokwi.toml a job holds: version, firmware and elf, with names from the fixed send/ layout."""
    lines = ["# Generated by wokwi-tool for one job; the project's own wokwi.toml is not changed.", "[wokwi]", "version = 1", f"firmware = '{firmware}'"]
    if elf is not None:
        lines.append(f"elf = '{elf}'")
    return "\n".join(lines) + "\n"


def write(cwd: Path, folder: Path, plan: dict[str, Any]) -> dict[str, Any]:
    """Copies the inputs into `folder/send`, writes the generated wokwi.toml, job.json and job.md; returns the job."""
    send = folder / SEND
    send.mkdir()
    files: list[dict[str, Any]] = []

    def add(role: str, source: Path | None, relative: str, sha256: str | None = None) -> None:
        target = send / relative
        if source is not None:
            _copy(source, target)
        digest = sha256_file(target)
        if sha256 is not None and digest != sha256:
            raise refused("job-changed", f"{relative} changed while it was copied.")
        files.append({
            "role": role,
            "path": f"{SEND}/{relative}",
            "source": workspace.relative(cwd, source) if source is not None else None,
            "sha256": digest,
            "bytes": target.stat().st_size,
            "transmitted": role in TRANSMITTED,
        })

    # The diagram and scenario hashes were taken before they were validated: the copy must be those very bytes.
    add("diagram", plan["diagramPath"], "diagram.json", plan.get("diagramSha256"))
    firmware, elf = plan["firmware"], plan["elf"]
    name = firmware_name(firmware["form"])
    if firmware["form"] == "esp-idf-flasher-args":
        add("config", cwd / firmware["path"], FLASH_CONFIG, firmware["sha256"])
        for part in firmware["parts"]:
            add("flash", cwd / part["path"], f"flash/{part['file']}", part["sha256"])
    else:
        add("firmware", cwd / firmware["path"], name, firmware["sha256"])
    elf_name = None
    if elf is not None and elf is not firmware:
        elf_name = ELF_NAME
        add("elf", cwd / elf["path"], elf_name, elf["sha256"])
    elif elf is firmware:
        elf_name = name
    if plan["scenario"] is not None:
        add("scenario", plan["scenario"]["path"], "scenario.yaml", plan["scenario"].get("sha256"))
    write_text(send / "wokwi.toml", config_text(name, elf_name))
    add("config", None, "wokwi.toml")
    scenario = plan["scenario"]
    job = {
        "format": FORMAT,
        "kind": JOB_KIND,
        "tool": f"{TOOL} {VERSION}",
        "runId": folder.name,
        "createdAt": stamp(),
        "cli": {"version": CLI_VERSION, "sha": CLI_SHA},
        "endpoint": ENDPOINT,
        "account": plan["account"],
        "project": plan["project"],
        "board": plan["board"],
        "firmware": {"form": firmware["form"], "sha256": firmware["sha256"], "origin": firmware["origin"], "buildMatch": plan["buildMatch"], **({"elfSha256": elf["sha256"]} if elf is not None else {})},
        "files": files,
        "transmittedBytes": sum(entry["bytes"] for entry in files if entry["transmitted"]),
        "assertions": {
            "scenario": {"name": scenario["name"], "steps": scenario["steps"], "commands": scenario["commands"]} if scenario else None,
            "expectText": plan["expectText"],
            "failText": plan["failText"],
        },
        "limits": {"virtualTimeoutMs": plan["virtualTimeoutMs"], "realBudgetS": plan["realBudgetS"], "attempts": 1},
        "outputs": {"serialLog": True, "vcd": plan["vcd"], "screenshot": plan["screenshot"]},
        "usage": USAGE,
        "note": NOTE,
    }
    write_json(folder / "job.json", job)
    write_text(folder / "job.md", markdown(job))
    return job


def markdown(job: dict[str, Any]) -> str:
    limits, assertions = job["limits"], job["assertions"]
    lines = [
        f"# Wokwi job {job['runId']}",
        "",
        f"> {job['note']}",
        "",
        f"- Cloud endpoint: `{job['endpoint']}` (wokwi-cli {job['cli']['version']})",
        f"- Account (stored Wokwi token): `{job['account']}`",
        f"- Board: `{job['board']['id']}` ({job['board']['type']})",
        f"- Virtual time limit: {limits['virtualTimeoutMs']} ms of simulated time; real-time budget: {limits['realBudgetS']} s; attempts: 1",
        f"- Usage: {job['usage']}",
        f"- Assertion: {'scenario ' + repr(assertions['scenario']['name']) if assertions['scenario'] else 'expect text ' + repr(assertions['expectText'])}" + (f"; fail text {assertions['failText']!r}" if assertions["failText"] else ""),
        "",
        f"Sent to Wokwi ({job['transmittedBytes']} bytes):",
        "",
        "| File | Role | Bytes | SHA-256 | Source |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| `{entry['path']}` | {entry['role']} | {entry['bytes']} | `{entry['sha256']}` | `{entry['source']}` |" for entry in job["files"] if entry["transmitted"]]
    lines += ["", "Used on this computer only:", ""]
    lines += [f"- `{entry['path']}` ({entry['role']}, {entry['bytes']} bytes, `{entry['sha256']}`)" for entry in job["files"] if not entry["transmitted"]]
    return "\n".join(lines) + "\n"


def _int_in(value: Any, low: int, high: int) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and low <= value <= high


def _text(value: Any) -> bool:
    return value is None or (isinstance(value, str) and 1 <= len(value) <= TEXT_LIMIT and not any(ord(c) < 32 or ord(c) == 127 for c in value))


def load(cwd: Path, spelled: Path, raw: str) -> tuple[Path, dict[str, Any], str]:
    """job.json and the SHA-256 of the bytes read, checked for kind and the form of every field run-scenario uses
    (job-invalid): a hand-written job gets no more than prepare-job could have written."""
    try:
        path = workspace.regular_file(cwd, raw, "--job", spelled)
    except workspace.PathRefused as error:
        raise refused("path", str(error)) from error
    try:
        data = path.read_bytes()
        job = json.loads(data.decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as error:
        raise refused("job-invalid", f"--job '{raw[:120]}' is not a job.json.") from error
    invalid = refused("job-invalid", f"--job '{raw[:120]}' is not a wokwi-tool job of format 1.")
    if not isinstance(job, dict) or job.get("kind") != JOB_KIND or job.get("format") != FORMAT:
        raise invalid
    limits, assertions, outputs = job.get("limits"), job.get("assertions"), job.get("outputs")
    board, firmware = job.get("board"), job.get("firmware")
    if (
        not isinstance(limits, dict)
        or not _int_in(limits.get("virtualTimeoutMs"), *VIRTUAL_RANGE)
        or not _int_in(limits.get("realBudgetS"), *REAL_RANGE)
        or not isinstance(job.get("files"), list)
        or not isinstance(job.get("account"), str)
        or not isinstance(assertions, dict)
        or not isinstance(outputs, dict)
        or not isinstance(board, dict)
        or not isinstance(board.get("id"), str)
        or not isinstance(board.get("type"), str)
        or not isinstance(firmware, dict)
        or firmware.get("form") not in (*FIRMWARE_FORMS, "esp-idf-flasher-args")
    ):
        raise invalid
    scenario = assertions.get("scenario")
    if (
        not (scenario is None or (isinstance(scenario, dict) and isinstance(scenario.get("name"), str)))
        or not _text(assertions.get("expectText"))
        or not _text(assertions.get("failText"))
        or (scenario is None) == (assertions.get("expectText") is None)
        or not isinstance(outputs.get("vcd"), bool)
    ):
        raise invalid
    screenshot = outputs.get("screenshot")
    if screenshot is not None and (
        not isinstance(screenshot, dict)
        or not isinstance(screenshot.get("part"), str)
        or not _int_in(screenshot.get("ms"), 0, limits["virtualTimeoutMs"])
    ):
        raise invalid
    return path, job, hashlib.sha256(data).hexdigest()


def _layout(job: dict[str, Any]) -> dict[str, str]:
    """The roles send/ may hold for this job, by path; flash parts are checked against flasher_args.json."""
    form = job["firmware"]["form"]
    roles = {f"{SEND}/diagram.json": "diagram", f"{SEND}/wokwi.toml": "config"}
    roles[f"{SEND}/{firmware_name(form)}"] = "config" if form == "esp-idf-flasher-args" else "firmware"
    if job["firmware"].get("elfSha256") is not None and form != "elf":
        roles[f"{SEND}/{ELF_NAME}"] = "elf"
    if job["assertions"].get("scenario") is not None:
        roles[f"{SEND}/scenario.yaml"] = "scenario"
    return roles


def verify(job_path: Path, job: dict[str, Any]) -> Path:
    """send/ holds exactly the fixed layout of this job, each file with its listed role, size and hash, and the
    generated wokwi.toml (job-changed); returns send/."""
    folder = job_path.parent
    send = folder / SEND
    changed = lambda message: refused("job-changed", message)  # noqa: E731
    form = job["firmware"]["form"]
    roles = _layout(job)
    listed: set[str] = set()
    entries: dict[str, dict[str, Any]] = {}
    for entry in job["files"]:
        relative = entry.get("path") if isinstance(entry, dict) else None
        if not isinstance(relative, str):
            raise changed("job.json lists a file without a path.")
        pure = PurePosixPath(relative)
        if pure.is_absolute() or ".." in pure.parts or pure.parts[:1] != (SEND,) or relative in entries:
            raise changed(f"job.json lists {relative[:120]}, which is not a file of send/.")
        flash = form == "esp-idf-flasher-args" and pure.parts[1:2] == ("flash",) and relative != f"{SEND}/{FLASH_CONFIG}"
        expected = "flash" if flash else roles.get(relative)
        if expected is None or entry.get("role") != expected or entry.get("transmitted") is not (expected in TRANSMITTED):
            raise changed(f"job.json lists {relative[:120]}, which is not part of a {form} job's layout.")
        path = folder / Path(*pure.parts)
        try:
            if path.is_symlink() or not path.is_file():
                raise changed(f"{relative} is missing or not a regular file.")
            if path.stat().st_size != entry.get("bytes") or sha256_file(path) != entry.get("sha256"):
                raise changed(f"{relative} differs from the prepared job.")
        except OSError as error:
            raise changed(f"{relative} cannot be read: {error.strerror or error}.") from error
        listed.add(os.path.normcase(str(path)))
        entries[relative] = entry
    missing = sorted(set(roles) - set(entries))
    if missing:
        raise changed(f"job.json does not list {missing[0]}.")
    if not send.is_dir() or send.is_symlink():
        raise changed("The job's send folder is missing.")
    for root, folders, names in os.walk(send):
        for name in folders:
            if (Path(root) / name).is_symlink():
                raise changed(f"send/ holds the link {name[:80]}.")
        for name in names:
            if os.path.normcase(str(Path(root) / name)) not in listed:
                raise changed(f"send/ holds {workspace.relative(folder, Path(root) / name)}, which the job does not list.")
    elf = ELF_NAME if f"{SEND}/{ELF_NAME}" in roles else (firmware_name(form) if form == "elf" else None)
    try:
        toml = (send / "wokwi.toml").read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise changed("send/wokwi.toml cannot be read.") from error
    if toml != config_text(firmware_name(form), elf):
        raise changed("send/wokwi.toml is not the configuration prepare-job generates for this job.")
    if form == "esp-idf-flasher-args":
        parts = {f"{SEND}/flash/{part['file']}" for part in flash_parts(folder, send / FLASH_CONFIG)}
        flashed = {relative for relative, entry in entries.items() if entry["role"] == "flash"}
        if parts != flashed:
            raise changed("send/flash/flasher_args.json names other files than the job lists.")
    return send


def revalidate(cwd: Path, spelled: Path, send: Path, job: dict[str, Any]) -> None:
    """The checks prepare-job made, again on the copies: one board equal to the job's, the screenshot part, the scenario."""
    found = diagram.structure(send / "diagram.json")
    if found["issues"] or found["boards"] != [{"id": job["board"]["id"], "type": job["board"]["type"]}]:
        raise refused("job-invalid", "The job's diagram is not valid or does not hold exactly the job's one board.")
    parts = {part["id"] for part in found["parts"]}
    screenshot = job["outputs"].get("screenshot")
    if screenshot is not None and screenshot["part"] not in parts:
        raise refused("job-invalid", "The job's screenshot part is not a part of its diagram.")
    if job["assertions"].get("scenario") is not None:
        scenario.load(cwd, spelled, str(send / "scenario.yaml"), parts)
